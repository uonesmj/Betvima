export class DomainError extends Error {
  readonly code: DomainErrorCode;
  readonly status: number;
  readonly details?: Record<string, unknown>;
  constructor(code: DomainErrorCode, message?: string, details?: Record<string, unknown>) {
    super(message ?? code);
    this.name = 'DomainError';
    this.code = code;
    this.status = STATUS[code] ?? 500;
    this.details = details;
  }
}

export const isDomainError = (e: unknown): e is DomainError => e instanceof DomainError;

/** Safe external error body. Internal stack traces never cross this boundary. */
export function toHttpError(error: unknown, correlationId: string): { status: number; body: Record<string, unknown> } {
  if (isDomainError(error)) {
    return {
      status: error.status,
      body: { ok: false, code: error.code, message: error.message, details: error.details ?? null, correlationId },
    };
  }
  return { status: 500, body: { ok: false, code: 'INTERNAL_ERROR', message: 'Unexpected error', correlationId } };
}
