const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({executablePath:'/usr/bin/chromium-browser',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  const page = await browser.newPage({viewport:{width:390,height:844}});
  await page.goto('http://127.0.0.1:3000/',{waitUntil:'networkidle',timeout:30000});
  console.log('PAGE_OK=',page.url()==='http://127.0.0.1:3000/');
  console.log('SEARCH_BUTTONS=',await page.locator('button[aria-label="Search"]').count());
  const btn=page.locator('button[aria-label="Search"]').first();
  console.log('SEARCH_VISIBLE=',await btn.isVisible().catch(()=>false));
  await btn.click();
  await page.waitForTimeout(300);
  const input=page.locator('input[aria-label="Search teams or leagues"]').first();
  console.log('INPUT_COUNT=',await input.count());
  console.log('INPUT_VISIBLE=',await input.isVisible().catch(()=>false));
  await input.fill('Levante');
  await page.waitForTimeout(1800);
  console.log('INPUT_VALUE=',await input.inputValue());
  console.log('LEVANTE_TEXT_COUNT=',await page.getByText(/Levante/i).count());
  console.log('MATCH_LINKS=',JSON.stringify(await page.locator('a[href^="/match/"]').allInnerTexts()));
  console.log('PORTAL_DROPDOWNS=',await page.locator('body > div').filter({hasText:/Levante/i}).count().catch(()=>-1));
  console.log('BODY_HAS_LEVANTE=',(await page.locator('body').innerText()).includes('Levante'));
  await browser.close();
})().catch(e=>{console.error('TEST_ERROR=',e.message);process.exit(1)});
